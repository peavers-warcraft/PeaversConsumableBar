#!/usr/bin/env python3
"""Regenerate src/Data/ForeverEnhancements.lua from WoW Forever's own game data.

The list it writes is every Forever item whose use enchants a weapon for a while:
sharpening stones, weightstones, wizard and mana oils, rogue poisons, imbue
scrolls and shield coatings. Why the bar needs it at all is explained at the top
of src/Core/Categories.lua; the short version is that Forever files most of
these under Consumable / Other, next to crates and quest writs, and nothing a
client API returns can tell them apart. The client's spell data can, so the
answer is read from there, here, ahead of time.

Run it again when a Forever patch adds weapon enhancements, and commit the
result. An item it has not seen yet is never filed wrongly, only by the game's
own subclass, which is what the bar did before this list existed.

    python3 scripts/forever_enhancements.py                  # newest Forever build
    python3 scripts/forever_enhancements.py --build 1.60.1.71139

Standard library only. The tables come from wago.tools, which publishes each
client build's DB2 tables as CSV. "wowf" is its product name for WoW Forever.
"""

import argparse
import csv
import io
import json
import pathlib
import sys
import urllib.request

WAGO = "https://wago.tools"
PRODUCT = "wowf"

# Its default Python user agent is refused with a 403.
USER_AGENT = "PeaversConsumableBar-datagen"

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "Data" / "ForeverEnhancements.lua"

# ItemEffect.TriggerType for "Use:".
TRIGGER_ON_USE = 0

# SpellEffect.Effect values that put a timed enchantment on an item.
# 54 is SPELL_EFFECT_ENCHANT_ITEM_TEMPORARY: stones, oils, coatings.
# 360 has no public name. Forever's rogue poisons and imbue scrolls use it, and
# like 54 its first misc value is the SpellItemEnchantment it applies.
TEMPORARY_ENCHANT_EFFECTS = {54, 360}

# Item classes a consumable bar can hold: Consumable, and Trade Goods, where a
# few Forever oils and stones are filed. Firestones and Spellstones are armour
# and the toxins left over from 2004 are Miscellaneous, so both stay out.
ITEM_CLASSES = {0, 7}

# SpellEquippedItems: what the spell may be used on.
WEAPON_CLASS = 2
# A subclass mask of fishing poles alone is a fishing lure. A lure goes on a
# pole, not on the weapon you pull with, so it is left where the game files it.
FISHING_POLE_ONLY = 1 << 20


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read().decode("utf-8")


def newest_build():
    builds = json.loads(fetch(f"{WAGO}/api/builds")).get(PRODUCT) or []
    if not builds:
        sys.exit(f"wago.tools lists no builds for {PRODUCT}")
    return max(builds, key=lambda build: build.get("created_at", ""))["version"]


def table(name, build):
    text = fetch(f"{WAGO}/db2/{name}/csv?build={build}")
    return list(csv.DictReader(io.StringIO(text)))


def collect(build):
    items = {int(row["ID"]): int(row["ClassID"]) for row in table("Item", build)}
    names = {int(row["ID"]): row["Display_lang"].strip() for row in table("ItemSparse", build)}

    effects = {int(row["ID"]): row for row in table("ItemEffect", build)}
    on_use = {}
    for row in table("ItemXItemEffect", build):
        effect = effects.get(int(row["ItemEffectID"]))
        if effect and int(effect["TriggerType"]) == TRIGGER_ON_USE:
            on_use.setdefault(int(row["ItemID"]), set()).add(int(effect["SpellID"]))

    enchanting = {
        int(row["SpellID"])
        for row in table("SpellEffect", build)
        if int(row["Effect"]) in TEMPORARY_ENCHANT_EFFECTS
    }

    on_weapons = {
        int(row["SpellID"])
        for row in table("SpellEquippedItems", build)
        if int(row["EquippedItemClass"]) == WEAPON_CLASS
        and int(row["EquippedItemSubclass"]) != FISHING_POLE_ONLY
    }

    found = {}
    for item_id, spells in on_use.items():
        # No name means no ItemSparse row: an item the client cannot show, so
        # one nobody can be carrying.
        if not names.get(item_id) or items.get(item_id) not in ITEM_CLASSES:
            continue
        if any(spell in enchanting and spell in on_weapons for spell in spells):
            found[item_id] = names[item_id]
    return found


def render(build, found):
    lines = [
        "local _, PCBar = ...",
        "",
        "-- GENERATED by scripts/forever_enhancements.py. Do not edit by hand: run the script.",
        f"-- WoW Forever {build}: every item whose use enchants a weapon for a while.",
        "-- Why the bar needs this list is at the top of src/Core/Categories.lua.",
        "",
        "PCBar.ForeverEnhancements = {",
    ]
    for item_id in sorted(found):
        # Names go in a comment, which ends at the line: nothing in one can
        # break out of it, quotes included.
        name = found[item_id].replace("\n", " ")
        lines.append(f"    [{item_id}] = true, -- {name}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--build", help="a Forever build such as 1.60.1.71139 (default: newest)")
    parser.add_argument("--output", type=pathlib.Path, default=OUTPUT)
    args = parser.parse_args()

    build = args.build or newest_build()
    found = collect(build)
    if not found:
        sys.exit(f"no temporary weapon enhancements found in {build}; refusing to write an empty list")

    args.output.write_text(render(build, found), encoding="utf-8")
    print(f"{len(found)} items from {PRODUCT} {build} -> {args.output}")


if __name__ == "__main__":
    main()
